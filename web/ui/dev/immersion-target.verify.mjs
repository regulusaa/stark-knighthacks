import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createEngine, parseHead, parseConv5 } from '../../core/steer/engine.js';
import { resolveClass, planTarget } from '../immersion/targeting.js';
const base=process.argv[2]||'http://localhost:3004';
assert.equal((await(await fetch(base+'/api/room')).json()).fixedRoom,null,'Use the local server; never replace the live display.');
const catalog=(await(await fetch(base+'/assets/steer/classes.json')).json()).classes;
assert.equal(resolveClass(catalog,'American curl'),null);
assert.equal(resolveClass(catalog,'TIGER CAT').classId,282);
const engine=createEngine(parseHead(await(await fetch(base+'/assets/steer/head.bin')).arrayBuffer()));
engine.setImage('ambig_cat',parseConv5(await(await fetch(base+'/assets/ambig_cat/conv5.bin')).arrayBuffer()));
const baseline=Array.from(engine.probs),plan=planTarget(engine,282,new Map());
assert.deepEqual(Array.from(engine.probs),baseline,'Suggestions must not change the model');
assert.equal(plan.reachesTop,true);
engine.apply(new Map(plan.steps.map(s=>[s.channel,s.scale])));
assert.equal(engine.argmax(),282);assert.ok(Math.abs(engine.probs[282]-plan.score)<1e-12);
console.log('PASS real class lookup; American curl unsupported; exact suggested recipe reaches tiger cat; planning restores all scores');
const b=await chromium.launch({args:['--use-angle=metal','--enable-gpu','--ignore-gpu-blocklist']}),errors=[];
const watch=p=>{p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error')errors.push(m.text())});};
try{
 const d=await b.newPage({viewport:{width:2560,height:1440}});watch(d);
 await d.goto(base+'/display?image=ambig_cat&pulseAt=done');await d.waitForFunction(()=>window.__starkReady&&window.__stark.relay?.room,null,{timeout:45000});
 const room=await d.evaluate(()=>__stark.relay.room);
 const h=await b.newPage({viewport:{width:1180,height:820},hasTouch:true});watch(h);
 await h.goto(`${base}/controller?room=${room}&role=host&key=test&workspace=immersion`);await h.waitForFunction(()=>window.__immersionControllerReady);
 const f=h.frames().find(f=>f.url().includes('/immersion/scene.html'));await f.waitForFunction(()=>window.__immersion.records.has('class:722'));
 await f.evaluate(()=>{__immersion.command({action:'select',key:'class:722'});__immersion.command({action:'extract',key:'class:722'});});
 await h.locator('.immersion-name').fill('American curl');
 await h.waitForFunction(()=>document.querySelector('.immersion-name-status').textContent.includes('not an output class'));
 assert.equal(await h.locator('.immersion-target').isVisible(),false);
 assert.match(await h.locator('.immersion-name-status').innerText(),/score above belongs to ping-pong ball/);
 assert.match(await f.evaluate(()=>__immersion.records.get('class:722').tip.node.label),/ping-pong ball.*note/);
 await h.locator('.immersion-name').fill('tiger cat');
 await h.waitForFunction(()=>document.querySelector('.immersion-target-score').textContent.includes('Rank'));
 assert.equal(await h.locator('.immersion-target').isVisible(),true);
 assert.match(await h.locator('.immersion-target-label').innerText(),/tiger cat/);
 const scores=await f.evaluate(()=>({original:__immersion.localEngine.probs[722],target:__immersion.localEngine.probs[282]}));assert.notEqual(scores.original,scores.target);
 assert.match(await h.locator('.immersion-target-guide').innerText(),/suggested edits make it the top answer/);
 assert.equal(await d.evaluate(()=>__stark.api.state.top1.classId),281,'Renaming alone must not change the shared model');
 await h.screenshot({path:'web/ui/.shots/immersion-target-original-1180x820.png'});
 await h.locator('[data-command="target-next"]').click();
 await d.waitForFunction(()=>__stark.api.state.top1.classId===282);
 await h.waitForFunction(()=>document.querySelector('.immersion-target-guide').textContent.includes('already the top answer'));
 await h.locator('[data-command="return"]').click();await d.waitForFunction(()=>__stark.api.state.focus?.classId===282);
 assert.equal(await f.evaluate(()=>__immersion.records.get('class:722').detached),false);
 assert.equal(await f.evaluate(()=>__immersion.records.get('class:722').classId),722,'Original model identity is retained');
 await h.screenshot({path:'web/ui/.shots/immersion-target-steered-1180x820.png'});
 console.log('PASS ping-pong → tiger cat target: own score/rank, exact guided shared flip, returning focuses tiger cat, original identity preserved');
 await h.locator('[data-command="reset-features"]').click();await d.waitForFunction(()=>__stark.api.state.top1.classId===281);
 await h.locator('.immersion-name').fill('Siamese cat');await h.waitForFunction(()=>document.querySelector('.immersion-target-guide').textContent.includes('does not reach the top answer'));
 assert.match(await h.locator('.immersion-target-guide').innerText(),/not drawn in the original Brain/);
 assert.equal(await h.locator('[data-command="target-focus"]').isVisible(),false);
 assert.equal(await d.evaluate(()=>__stark.api.state.top1.classId),281);
 console.log('PASS unachieved target recipe reports its measured limit; absent Brain targets cannot offer broken focus');
 for(const [width,height] of [[390,844],[844,390],[320,568],[1180,820]]){await h.setViewportSize({width,height});assert.equal(await h.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);}
 await h.setViewportSize({width:390,height:844});await h.screenshot({path:'web/ui/.shots/immersion-target-390x844.png'});
 assert.deepEqual(errors,[]);console.log('PASS Immersion target integration, four viewport bounds, 0 console errors');
}finally{await b.close();}
